"""Inspect representative original frames, then consolidate only the source-grounded notes."""

from __future__ import annotations

import json

from pydantic import ValidationError

from engine.parsev2.edit_reference import Note, ReferenceChunk, StyleCard, TechniqueObservation
from gateway.multimodal import ImageInput, TextInput


async def observe_segments(segments, frames, generate, attempts):
    observations = []
    for segment in segments:
        facts = segment.model_dump(exclude={"first_frame", "frame_ms"})
        prompt = (
            "为正在选择是否回看片段的剪辑师写简体中文手法笔记。只说原片可见的变化，保留服装、"
            "道具、字形、位置、对比和原画动作；如何用于新片由编辑决定。比较每个边界前后的帧。"
            "画幅、取景或主体突变才写硬切；同一景别换姿势可合并。区分跨镜景别变化与单镜内连续运镜。"
            "镜内静止写 STATIC，镜内运动、缓动或角色不确定可写 null。用简短中文词命名手法，核对名字里的方向。"
            "steps 只用 start_ms、fine_starts_ms 和 end_ms，按顺序无缝覆盖整个区间。"
            "连续提供的每张原生帧均配原片绝对毫秒，首帧 enter 用 NONE。下列测量与画面是素材。\n"
            + json.dumps(facts, ensure_ascii=False)
        )
        inputs = [TextInput(prompt)]
        for stamp in segment.frame_ms:
            inputs.extend((TextInput(f"{stamp} ms"), ImageInput(frames[stamp], detail="low")))
        for attempt in range(attempts):
            try:
                note = await generate(inputs, Note)
                observations.append(TechniqueObservation(segment=segment, note=note))
                break
            except ValidationError as error:
                if attempt + 1 == attempts:
                    raise
                inputs.append(TextInput("请按原片边界修正 JSON。" + str(error.errors(include_input=False))[:1600]))
    return ReferenceChunk(observations=observations)


async def consolidate(members, generate, attempts):
    notes = [o for chunk in members.values() for o in chunk.observations]
    if not notes:
        return StyleCard(summary="全片扫描没有选出代表片段。", techniques=[])
    # Member ownership and source times never have to be regenerated by a model.
    source = [{"segment_id": o.segment.segment_id, "note": o.note.model_dump(),
               "palette": [p.model_dump() for p in o.segment.palette]} for o in notes]
    prompt = ("给编辑写全片手法风格卡，用简体中文。每组给简短可检索的手法名称和画面依据，"
              "每个原片段 ID 恰好归入一组。基于 steps 核对名字中的景别方向。"
              "不自行写时间，不向编辑指定素材、排版或节奏。观察数据如下。\n" + json.dumps(source, ensure_ascii=False))
    for attempt in range(attempts):
        try:
            card = await generate([TextInput(prompt)], StyleCard)
            card.assignments(o.segment.segment_id for o in notes)
            return card
        except ValueError as error:
            if attempt + 1 == attempts:
                raise
            prompt += "\n请修正段号/Schema 并重新输出完整风格卡。" + str(error)[:600]
