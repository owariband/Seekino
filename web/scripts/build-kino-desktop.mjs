// Run with `node web/scripts/build-kino-desktop.mjs` after changing Kino's Web engine.
// Qt and Node both load ES modules. Only the developer generating the module needs TypeScript.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const engine = fileURLToPath(new URL('../src/shared/kino/engine.ts', import.meta.url));
const output = new URL('../../desktop/ui/KinoEngine.mjs', import.meta.url);
const build = mkdtempSync(join(tmpdir(), 'kino-engine-'));
try {
  const compiler = new URL('../node_modules/typescript/bin/tsc', import.meta.url);
  execFileSync(process.execPath, [fileURLToPath(compiler), '--target', 'ES2017', '--module', 'ES2020',
    '--lib', 'ES2022', '--skipLibCheck', '--outDir', build, engine], { stdio: 'inherit' });
  const hash = createHash('sha256').update(readFileSync(engine, 'utf8').replaceAll('\r\n', '\n')).digest('hex');
  const header = `// Generated by web/scripts/build-kino-desktop.mjs from engine.ts (SHA-256 ${hash}).\n`;
  writeFileSync(output, header + readFileSync(join(build, 'engine.js'), 'utf8'));
} finally {
  rmSync(build, { recursive: true, force: true });
}
