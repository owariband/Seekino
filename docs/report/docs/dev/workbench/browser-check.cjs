// Read-only browser checks for docs/dev/workbench.html.
// Usage: node docs/report/docs/dev/workbench/browser-check.cjs [output-dir]
// WORKBENCH_PLAYWRIGHT_PATH may point to a playwright package; defaults to web/node_modules/playwright.
const path=require('node:path'),os=require('node:os'),fs=require('node:fs'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const root=process.env.WORKBENCH_REPO_ROOT||path.resolve(__dirname,'../../../../..');
const {chromium}=require(process.env.WORKBENCH_PLAYWRIGHT_PATH||path.join(root,'web/node_modules/playwright'));
const source=path.join(root,'docs/dev/workbench.html'),output=process.argv[2]||path.join(os.tmpdir(),'seekino-workbench-check');
fs.mkdirSync(output,{recursive:true});
const data=JSON.parse(fs.readFileSync(source,'utf8').match(/<script id="workbench-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
const ms=data.milestones[0],gates=data.gates.filter(g=>g.milestone===ms.id);
const count=s=>gates.filter(g=>g.status===s).length;
const p0=data.cards.filter(c=>c.milestone===ms.id&&c.priority==='P0');
const warn=data.cards.filter(c=>c.status==='done'&&c.tags.some(t=>/待核对|待验收|Draft|待合并|待决策/.test(t))).length+data.cards.filter(c=>c.priority==='P0'&&c.status!=='done'&&!c.due).length;
const checks=[],errors=[],requests=[];
const ok=(name,condition=true)=>{assert.ok(condition,name);checks.push(name);console.log('PASS '+name)};
const observe=page=>{page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url())})};
const text=async(page,sel)=>(await page.locator(sel).first().textContent()).replace(/\s+/g,' ');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});await context.setOffline(true);
  const stale={...data,revision:data.revision+1000,cards:data.cards.map(c=>({...c,title:'OLD-DRAFT '+c.title}))};
  await context.addInitScript(draft=>{localStorage.setItem('seekino-kanban-draft-v1:'+location.pathname,JSON.stringify(draft))},stale);
  const page=await context.newPage();observe(page);await page.goto(pathToFileURL(source).href);
  ok('Overview is the default view',await page.locator('#view-overview').isVisible()&&!(await page.locator('#view-board').isVisible()));
  ok(`Hero shows ${count('pass')}/${gates.length} gates passed`,(await text(page,'.hero-num')).replace(/\s/g,'')===`${count('pass')}/${gates.length}`);
  ok('Gate legend matches data',(await text(page,'.hero .legend')).replace(/\s/g,'')===`通过${count('pass')}未通过${count('fail')}待测${count('untested')}`);
  const kpi=async label=>(await page.locator('.kpi',{hasText:label}).locator('.kpi-value').textContent()).replace(/\s/g,'');
  ok('Open P0 tile matches data',await kpi('未完成 P0')===`${p0.filter(c=>c.status!=='done').length}/${p0.length}`);
  ok('READY course tile matches data',await kpi('READY 课程')===`${ms.courses.filter(c=>c.ready).length}/${ms.courses.length}`);
  ok('Known cost shows unknown calls instead of zero',(await text(page,'.kpi:has-text("已知解析费用")')).includes('69 次调用费用未知'));
  ok('Consistency tile matches computed warnings',await kpi('状态矛盾')===String(warn));
  ok(`Loop map has ${ms.stages.length} stages`,await page.locator('.route .stage').count()===ms.stages.length&&await page.locator('.stepper .step').count()===ms.stages.length);
  ok('Watching stage fails because its gates fail',await page.locator('.route .stage').nth(4).getAttribute('data-state')==='fail');
  ok('Learning summary is marked out of milestone',await page.locator('.route .stage').last().getAttribute('data-state')==='out');
  const dues=[...new Set(data.cards.filter(c=>c.milestone===ms.id&&c.type!=='module'&&c.status!=='done'&&c.due).map(c=>c.due))].sort();
  ok('Urgent work is grouped by due date',await page.locator('.urgent-grid .day').count()===dues.length);
  ok('Blocked work names its upstream card',(await text(page,'.task-row:has-text("LOOP-04")')).includes('等待 LOOP-03'));
  ok('Repository data wins over a legacy draft',!(await page.locator('body').textContent()).includes('OLD-DRAFT'));
  ok('No save, export, import or editing controls',await page.locator('[data-action="save"],[data-action="add"],[data-action="edit"],[data-action="import"],input[type="file"],#editor-dialog,[draggable="true"]').count()===0);
  ok('Desktop overview has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:output+'/overview.png',fullPage:true});
  await page.locator('.route .chip[data-gate="RT07"]').click();
  ok('Gate chip opens gate detail',await page.locator('#detail-id').textContent()==='RT07'&&(await text(page,'#detail-content')).includes('未通过'));
  ok('Gate detail links the card that drives it',await page.locator('#detail-content [data-related="LOOP-05"]').count()===1);
  await page.locator('#detail-content [data-related="LOOP-05"]').click();
  ok('Related navigation opens the card',await page.locator('#detail-id').textContent()==='LOOP-05');
  await page.locator('[data-close="detail-dialog"]').click();
  await page.locator('.route [data-open="LOOP-04"]').first().click();
  ok('Card detail shows blockers and management fields',(await text(page,'#detail-content')).includes('被这些工作阻塞')&&(await text(page,'#detail-content')).includes('截止'));
  await page.screenshot({path:output+'/detail.png'});
  await page.locator('[data-close="detail-dialog"]').click();
  await page.locator('#views [data-view="board"]').click();
  ok('Board view shows all cards',(await page.locator('#result-label').textContent()).startsWith(data.cards.length+' 张'));
  await page.locator('[data-category-filter="parse"]').click();
  ok('Board has four status columns',await page.locator('#lane-parse .column').count()===4);
  ok('Verifying column holds migrated cards',await page.locator('#lane-parse .column[data-status="verifying"] .work-card').count()===data.cards.filter(c=>c.category==='parse'&&c.status==='verifying').length);
  await page.locator('[data-category-filter="all"]').click();
  for(const type of ['module','requirement','task']){await page.locator('[data-type-filter="'+type+'"]').click();ok(type+' type filter count',await page.locator('.work-card:visible').count()===data.cards.filter(c=>c.type===type).length)}
  await page.locator('[data-type-filter="all"]').click();
  await page.locator('#milestone-only').click();
  ok('Milestone filter shows milestone cards only',await page.locator('.work-card:visible').count()===data.cards.filter(c=>c.milestone===ms.id).length);
  await page.locator('#milestone-only').click();
  await page.locator('#search').fill('PR-25');await page.locator('[data-open="PR-25"]').click();
  ok('Card tagged awaiting verification is VERIFYING',(await page.locator('.detail-status').textContent()).startsWith('VERIFYING'));
  ok('PR links remain available',await page.locator('#detail-content a[href="https://github.com/owariband/Seekino/pull/25"]').count()===1);
  await page.locator('[data-close="detail-dialog"]').click();await page.locator('#search').fill('');
  ok('Desktop board has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:output+'/board.png'});
  await page.locator('#views [data-view="gates"]').click();
  ok('Gate table lists every gate',await page.locator('#gate-table tr.gate-row').count()===gates.length);
  await page.locator('[data-gate-filter="fail"]').click();
  ok('Gate filter shows failed gates',await page.locator('#gate-table tr.gate-row').count()===count('fail'));
  await page.locator('[data-gate-filter="all"]').click();
  await page.screenshot({path:output+'/gates.png',fullPage:true});
  await context.close();
  const mobile=await browser.newContext({viewport:{width:375,height:812},isMobile:true});await mobile.setOffline(true);
  const m=await mobile.newPage();observe(m);await m.goto(pathToFileURL(source).href);
  ok('Mobile view switcher is visible',await m.locator('#mobile-views').isVisible());
  ok('Mobile overview has no horizontal overflow',await m.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await m.screenshot({path:output+'/mobile.png',fullPage:true});
  await m.locator('#mobile-views [data-view="gates"]').click();
  ok('Mobile gates view renders',await m.locator('#gate-table tr.gate-row').count()===gates.length);
  await mobile.close();
  ok('No JavaScript page errors',errors.length===0);
  ok('No network requests while loading',requests.length===0);
  fs.writeFileSync(output+'/results.json',JSON.stringify({checkedAt:new Date().toISOString(),revision:data.revision,checks,errors,requests},null,2));
  console.log(`${checks.length} checks passed`);
 }finally{await browser.close()}
})().catch(e=>{console.error('FAIL',e.message,errors);process.exit(1)});
